function toPhones(source: Record<string, readonly CatalogueRow[]>): PtaPhone[] {
  return Object.entries(source).flatMap(([brand, rows]) =>
    rows.map(([model, variant, cnfUsd]) => ({
      brand,
      deviceKind: classifyPtaPhone(brand, model),
      model,
      variant,
      cnfUsd,
    })),
  );
}

