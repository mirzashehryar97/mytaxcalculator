/**
 * Per-model customs values published by the Directorate General of Customs
 * Valuation under section 25A of the Customs Act 1969. Transcribed from the
 * rendered pages of the rulings, not from their text layer — the scans OCR
 * badly enough to turn 215 into `2t5` and 1050 into `I 050`.
 *
 * A ruling value is a **floor**, not a price. Where the declared or invoice
 * value is higher, section 25(1) makes the assessment on the higher figure, so
 * the form takes a declared value that overrides these.
 *
 * Sources, read together because each supersedes the last only within its own
 * scope:
 *   - **VR 1999/2025** (22 Apr 2025) — new Apple handsets. Supersedes VR 1834
 *     "to the extent of New IPhone (Apple) Mobile Phones". 187 serials.
 *   - **VR 1834/2023** (5 Dec 2023) — new handsets, every other brand.
 *     Annexure-I, serials 1 to 1160.
 *   - **VR 2070/2026** (20 Apr 2026) — old and used handsets. 62 serials.
 *     Replaced VR 2035/2026, which a Director General rescinded by
 *     Order-in-Revision No. 05/2026 of 3 April 2026.
 *
 * Neither new-phone ruling reaches past the Galaxy S23 and the iPhone 16, so a
 * newer handset has no official value at all and the form falls through to
 * asking for one. Do not fill that gap with a retail price: every third-party
 * "PTA tax" calculator does, and a C&F value normally sits below MSRP.
 *
 * Colour variants are collapsed — the rulings price every colour of a storage
 * tier identically. The one exception is VR 1999 serial 146, iPhone 11 Pro Max
 * 256GB in space grey, printed at 618 where the other three colours read 578;
 * the majority figure is used and the anomaly is recorded in calculator-docs.
 *
 * Memory configurations are normalised into the variant column. VR 1834 writes
 * them six different ways — its own column, `S10 PLUS-128`, `A-51 8GB`,
 * `12 8+256`, `3.2 (3/32 GB)`, `REDMI NOTE 8 (4GB / 64GB)` — and 29 serials use
 * the name rather than the column, which split one handset across several
 * "models" in the picker. Those 29 are rewritten to `model` + `4 GB + 64 GB`
 * form; no value moved and no configuration was invented, so a row printed with
 * storage only (`S10 PLUS-128`) becomes `128 GB` and never gains a RAM figure.
 * Hyphens that are part of a name — Nokia `X2-01`, `Galaxy ALPHA-015`,
 * `Note-20 Ultra`, `itel-14 Max` — are left exactly as printed.
 */

/** `[model, variant, cnfUsd]` — variant is `''` where the ruling lists one row. */
